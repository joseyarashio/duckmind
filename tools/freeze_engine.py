#!/usr/bin/env python3
"""Freeze a Duck Core engine revision into ``src/duckmind/engines/<rev>/`` (spec §7.6, phase-4
design A6).

A duck keeps the engine it was born on. Old ducks (a saved Config without ``engine_rev``) replay
on a frozen copy of the v4 engine forever, so their history never changes when Duck Core does.
This script makes that copy from git, never from the working tree:

* every file comes from ``git show <commit>:<path>`` (the 16 Duck Core modules, ``provenance.py``
  and the three ``expression_sweep`` modules the engine reads its caps with);
* the only change is the import path: ``duckmind.duckcore`` → ``duckmind.engines.v4_0.duckcore``
  (and the same for ``provenance`` and ``expression_sweep``), plus a one-line header comment. The
  script proves it: each rewritten file parses to the same syntax tree as the original once the
  import paths are mapped back, and every import of the copy stays inside the copy;
* ``MANIFEST.json`` records, per file, the git blob, the SHA-256 of the original and of the copy.
  ``tests/test_engine_frozen.py`` checks the copy against it on every run.

Usage (from anywhere; git must have the commit)::

    python tools/freeze_engine.py            # (re)write src/duckmind/engines/v4_0/
    python tools/freeze_engine.py --check    # exit 1 if the copy on disk differs from git

Nothing here is ever edited by hand. To change what an old duck does, you do not: a new
behaviour is a new engine revision.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENGINES = ROOT / "src" / "duckmind" / "engines"
GENERATOR = "tools/freeze_engine.py"
MANIFEST = "MANIFEST.json"
MANIFEST_FORMAT = "duckmind-frozen-engine-v1"

DUCKCORE_MODULES = (
    "__init__",
    "api",
    "commands",
    "content",
    "daycycle",
    "engine",
    "excursion",
    "fixed",
    "graph",
    "memory",
    "moments",
    "narrate",
    "nest",
    "query",
    "rng",
    "routines",
)


@dataclass(frozen=True)
class Revision:
    rev: str
    commit: str
    # (path in the repo at ``commit``, path inside the frozen package)
    files: tuple[tuple[str, str], ...]
    # top-level duckmind modules and packages the copy carries (the import rewrite's domain)
    carried: tuple[str, ...]

    @property
    def package(self) -> str:
        return f"duckmind.engines.{self.rev}"


REVISIONS = {
    "v4_0": Revision(
        rev="v4_0",
        commit="79cc25d66ecc9c06442c8204f600204ef892ba18",
        files=(
            *((f"src/duckmind/duckcore/{m}.py", f"duckcore/{m}.py") for m in DUCKCORE_MODULES),
            ("src/duckmind/provenance.py", "provenance.py"),
            ("src/duckmind/expression_sweep/__init__.py", "expression_sweep/__init__.py"),
            ("src/duckmind/expression_sweep/clips.py", "expression_sweep/clips.py"),
            ("src/duckmind/expression_sweep/envelope.py", "expression_sweep/envelope.py"),
            ("src/duckmind/expression_sweep/looks.py", "expression_sweep/looks.py"),
        ),
        carried=("duckcore", "provenance", "expression_sweep"),
    )
}


def _init_text(revision: Revision) -> str:
    return f'''# Generated by {GENERATOR}; do not edit.
"""Duck Core engine {revision.rev}, frozen: the v4 duck exactly as commit
{revision.commit[:7]} left it (spec §7.6, phase-4 design A6).

A saved duck without ``engine_rev`` is a v4 duck and replays on this copy forever, so its
history never changes when Duck Core does. The copy is made from git by
``{GENERATOR}``; the only change from the original files is the import path
(``duckmind.duckcore`` → ``{revision.package}.duckcore``, the same for ``provenance``
and ``expression_sweep``). ``MANIFEST.json`` holds every file's SHA-256 and
``tests/test_engine_frozen.py`` checks them. Never edit these files: a new behaviour is a new
engine revision.
"""

REV = "{revision.rev}"
COMMIT = "{revision.commit}"
'''


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _git(*args: str) -> bytes:
    done = subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, check=False)
    if done.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed: {done.stderr.decode(errors='replace')}")
    return done.stdout


def _rewrite(text: str, revision: Revision) -> tuple[str, int]:
    """The file with its imports of the carried modules pointed into the frozen package."""
    names = "|".join(re.escape(name) for name in revision.carried)
    pattern = re.compile(rf"^(\s*(?:from|import)\s+)duckmind\.({names})\b", re.MULTILINE)
    return pattern.subn(rf"\1{revision.package}.\2", text)


def _unfrozen(tree: ast.AST, revision: Revision) -> ast.AST:
    """The tree with the frozen import paths mapped back to the originals (in place)."""
    prefix = revision.package + "."
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith(prefix):
            node.module = "duckmind." + node.module.removeprefix(prefix)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.startswith(prefix):
                    alias.name = "duckmind." + alias.name.removeprefix(prefix)
    return tree


def _imports(tree: ast.AST, module: str, is_package: bool) -> list[tuple[str, int]]:
    """(absolute module, line) of every import in the tree, relative ones resolved."""
    package = module if is_package else module.rpartition(".")[0]
    found: list[tuple[str, int]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found += [(alias.name, node.lineno) for alias in node.names]
        elif isinstance(node, ast.ImportFrom):
            base = node.module or ""
            if node.level:
                parts = package.split(".")
                base = ".".join([*parts[: len(parts) - node.level + 1], *filter(None, [base])])
            found.append((base, node.lineno))
        elif isinstance(node, ast.Call) and node.args and isinstance(node.args[0], ast.Constant):
            func = node.func
            name = func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", "")
            if name in {"import_module", "__import__"} and isinstance(node.args[0].value, str):
                found.append((node.args[0].value, node.lineno))
    return found


def _module_name(revision: Revision, path: str) -> tuple[str, bool]:
    parts = path.removesuffix(".py").split("/")
    is_package = parts[-1] == "__init__"
    if is_package:
        parts.pop()
    return ".".join([revision.package, *parts]), is_package


def build(revision: Revision) -> tuple[dict[str, bytes], dict[str, object], str]:
    """{path inside the frozen package: bytes}, the manifest and the tree hash, all from git."""
    header = (
        "# Frozen Duck Core engine {rev}: generated by {gen} from {commit}:{src}; do not edit.\n"
    )
    out: dict[str, bytes] = {}
    entries: list[dict[str, object]] = []
    for source, target in revision.files:
        original = _git("show", f"{revision.commit}:{source}")
        blob = _git("rev-parse", f"{revision.commit}:{source}").decode().strip()
        text = original.decode("utf-8")
        rewritten, count = _rewrite(text, revision)
        rewritten = (
            header.format(rev=revision.rev, gen=GENERATOR, commit=revision.commit[:7], src=source)
            + rewritten
        )
        # The only change is the import path: same syntax tree once it is mapped back.
        before = ast.dump(ast.parse(text, filename=source))
        after = ast.dump(_unfrozen(ast.parse(rewritten, filename=target), revision))
        if before != after:
            raise SystemExit(f"{source}: the rewrite changed more than import paths")
        data = rewritten.encode("utf-8")
        out[target] = data
        entries.append(
            {
                "path": target,
                "from": source,
                "blob": blob,
                "source_sha256": _sha256(original),
                "sha256": _sha256(data),
                "import_rewrites": count,
            }
        )
    init = _init_text(revision).encode("utf-8")
    out["__init__.py"] = init
    entries.append(
        {
            "path": "__init__.py",
            "from": None,
            "blob": None,
            "source_sha256": None,
            "sha256": _sha256(init),
            "import_rewrites": 0,
        }
    )
    _check_closed(revision, out)
    entries.sort(key=lambda entry: str(entry["path"]))
    tree = tree_sha256({str(e["path"]): str(e["sha256"]) for e in entries})
    manifest: dict[str, object] = {
        "format": MANIFEST_FORMAT,
        "about": (
            f"Duck Core engine {revision.rev}, frozen from git commit {revision.commit} by "
            f"{GENERATOR}. Every file's SHA-256 is checked by tests/test_engine_frozen.py; "
            "never edit the copy (a new behaviour is a new engine revision)."
        ),
        "rev": revision.rev,
        "commit": revision.commit,
        "package": revision.package,
        "rewrite": {f"duckmind.{name}": f"{revision.package}.{name}" for name in revision.carried},
        "tree_sha256": tree,
        "files": entries,
    }
    return out, manifest, tree


def tree_sha256(hashes: dict[str, str]) -> str:
    """One hash for the whole copy: SHA-256 over "path sha256" lines in path order."""
    lines = "".join(f"{path} {digest}\n" for path, digest in sorted(hashes.items()))
    return _sha256(lines.encode("utf-8"))


def _check_closed(revision: Revision, files: dict[str, bytes]) -> None:
    """Every duckmind import of the copy is a module of the copy (it never reaches back)."""
    modules = {_module_name(revision, path)[0] for path in files}
    problems = []
    for path, data in sorted(files.items()):
        module, is_package = _module_name(revision, path)
        tree = ast.parse(data.decode("utf-8"), filename=path)
        for name, line in _imports(tree, module, is_package):
            if name != "duckmind" and not name.startswith("duckmind."):
                continue
            # (``from pkg import module`` arrives here as the package itself.)
            if name not in modules:
                where = "not carried" if name.startswith(revision.package + ".") else "outside"
                problems.append(f"{path}:{line} imports {name} ({where} the frozen copy)")
    if problems:
        raise SystemExit("the frozen copy is not closed:\n" + "\n".join(problems))


def manifest_bytes(manifest: dict[str, object]) -> bytes:
    return (json.dumps(manifest, ensure_ascii=False, indent=1) + "\n").encode("utf-8")


def on_disk(folder: Path) -> dict[str, bytes]:
    """{path: bytes} of every file in a frozen package (bytecode caches left out)."""
    return {
        path.relative_to(folder).as_posix(): path.read_bytes()
        for path in sorted(folder.rglob("*"))
        if path.is_file() and "__pycache__" not in path.parts
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--rev", default="v4_0", choices=sorted(REVISIONS))
    parser.add_argument("--check", action="store_true", help="compare with disk, write nothing")
    parser.add_argument("--out", default=str(ENGINES), help="the engines/ folder")
    args = parser.parse_args(argv)
    revision = REVISIONS[args.rev]
    folder = Path(args.out) / revision.rev
    files, manifest, tree = build(revision)
    want = {**files, MANIFEST: manifest_bytes(manifest)}
    have = on_disk(folder) if folder.exists() else {}
    changed = sorted(path for path in want if have.get(path) != want[path])
    extra = sorted(set(have) - set(want))
    if args.check:
        for path in changed:
            print(f"DIFFERS {path}" if path in have else f"MISSING {path}")
        for path in extra:
            print(f"EXTRA   {path}")
        ok = not changed and not extra
        print(
            f"{revision.rev}: {len(want)} files, tree {tree[:16]}… "
            + ("identical to git" if ok else "DIFFERENT from git")
        )
        return 0 if ok else 1
    for path in extra:
        (folder / path).unlink()
    for path in changed:
        target = folder / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(want[path])
    print(
        f"{revision.rev}: wrote {len(changed)} of {len(want)} files, removed {len(extra)}; "
        f"tree {tree[:16]}…"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
