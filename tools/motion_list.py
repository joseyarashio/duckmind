def cell(text: Any) -> str:
    """One Markdown table cell: no pipes, no line breaks."""
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def table(head: list[str], rows: list[list[Any]]) -> list[str]:
    out = ["| " + " | ".join(cell(h) for h in head) + " |", "|" + " --- |" * len(head)]
    for row in rows:
        if len(row) != len(head):
            raise ValueError(f"row of {len(row)} cells under {len(head)} heads: {row!r}")
        out.append("| " + " | ".join(cell(c) for c in row) + " |")
    return out


def js_block(text: str, name: str) -> str:
    found = re.search(rf"const {name} = \{{(.*?)\n  \}};", text, re.S)
    if found is None:
        raise SystemExit(f"motion_list: no `const {name} = {{ … }}` block in {NEURO_JS.name}")
    return found.group(1)


class Reg:
    """The registries, read once. Language-free."""

    def __init__(self) -> None:
        src = str(ROOT / "src")
        if sys.path[0] != src:
            sys.path.insert(0, src)
        from duckmind.curiosity import prims
        from duckmind.i18n.catalog import read_catalog
        from duckmind.i18n.message import render
        from duckmind.neuro import (
            brain,
            command_brain,
            command_words,
            contract,
            emotions,
            errand,
            motions,
            motor,
            tricks,
        )
        from duckmind.neuro import select as sel
        from duckmind.neuro.integration import install_default_skills
        from duckmind.skilltrain import guard, motion_table
        from duckmind.skilltrain import table as skill_table

        install_default_skills()
        self.prims, self.brain, self.cb, self.cw = prims, brain, command_brain, command_words
        self.c, self.emo, self.errand, self.motions = contract, emotions, errand, motions
        self.motor, self.tricks, self.sel = motor, tricks, sel
        self.g, self.mt, self.slots = guard, motion_table, skill_table.MAX_SKILLS
        self.read_catalog, self._render = read_catalog, render
        self.behaviours: dict[str, Any] = dict(contract.BEHAVIOURS)
        self.rules = {
            n: r for n, r in guard.DEFAULT_RULES.items() if r.family not in RELEASE_FAMILIES
        }
        self.words, self.brain_words, self.no_brain = self._read_js()
        self.installed = self._installed()
        self.entries_of = self._entries_of()
        self.users_of = self._users_of()
        self._check_brain_users()
        self.after_of: dict[str, list[str]] = defaultdict(list)
        for act, (entry, _chance, _patience) in guard.BRAIN_AFTER.items():
            self.after_of[entry].append(act)
        self.claims_of: dict[str, list[str]] = defaultdict(list)  # behaviour -> verbs
        for verb, act in command_brain.BEHAVIOUR_OF.items():
            self.claims_of[act].append(verb)
        self.trick_acts = {command_brain.BEHAVIOUR_OF[v] for v in command_words.TRICKS}
        self.trick_only = {act for act in self.trick_acts if not sel.W.get(act)}
        self.motion_by_entry: dict[str, list[Any]] = defaultdict(list)
        for m in motions.MOTIONS:
            self.motion_by_entry[m.entry].append(m)
        self.s2_ids = [
            *POSTURE_CHANGE,
            *(b for b, s in self.behaviours.items() if s.family == "rest"),
        ]
        reflex_acts = [
            b
            for b, s in self.behaviours.items()
            if s.family == "reflex" and b not in contract.REFLEXES
        ]
        self.s5_ids = [*contract.REFLEXES, *reflex_acts]
        taken = {*self.s2_ids, *(b for b in self.s5_ids if b in self.behaviours)}
        self.s7_ids = {
            fam: [b for b, s in self.behaviours.items() if s.family == fam and b not in taken]
            for fam in FAMILY_ORDER
        }
        listed = [*taken, *(b for ids in self.s7_ids.values() for b in ids)]
        if sorted(listed) != sorted(self.behaviours):
            missing = sorted(set(self.behaviours) - set(listed))
            raise SystemExit(f"motion_list: acts in no section (a new family?): {missing}")

    def _read_js(self) -> tuple[dict[str, tuple[str, str]], dict[str, str], str]:
        text = NEURO_JS.read_text(encoding="utf-8")
        words = {
            m.group(1): (m.group(2), m.group(3))
            for m in re.finditer(
                r'(\w+): \{ name: "([^"]+)", limit: "([^"]+)" \}', js_block(text, "MOTION_WORDS")
            )
        }
        brain = {
            m.group(1): m.group(2)
            for m in re.finditer(r'(\w+): "(page\.[\w.]+)"', js_block(text, "MOTION_BRAIN"))
        }
        none = re.search(r'const NO_BRAIN = "([^"]+)"', text)
        if none is None:
            raise SystemExit("motion_list: no NO_BRAIN in neuro.js")
        for m in self.motions.MOTIONS:
            if m.id not in words:
                raise SystemExit(f"motion_list: neuro.js MOTION_WORDS has no words for {m.id!r}")
        for name in self.emo.ORDER:
            if self.emo.ID_PREFIX + name not in words:
                raise SystemExit(
                    f"motion_list: neuro.js MOTION_WORDS has no words for emotion {name!r}"
                )
        return words, brain, none.group(1)

    def _installed(self) -> set[str]:
        """The entries of the table that is installed (robotd takes 30; the picker takes the nearest)."""
        paths = {role: f"{role}.onnx" for role in self.mt.FILES}
        return {e.name for e in self.mt.entries(paths, "velstand.onnx")}

    def _entries_of(self) -> dict[str, dict[str, list[str]]]:
        """Act -> posture -> the trained entries it asks for (the picker's tables and rules)."""
        g = self.g
        out: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))

        def add(act: str, postures: tuple[str, ...], entries: list[str]) -> None:
            for p in postures:
                out[act][p].extend(e for e in entries if e not in out[act][p])

        for act, by in g.BRAIN_SCRIPTS.items():
            for posture, (entry, _hold, _end) in by.items():
                add(act, (posture,), [entry])
        for act, by in g.SkillPicker().mapping.items():
            for posture, entry in by.items():
                # a harder variant of the picked entry (shake_2 for shake_1) is used by the same act
                harder = [x for x in g.DEFAULT_RULES if g.lower(x) == entry]
                add(act, (posture,), [entry, *harder])
        # what SkillPicker.pick and the body link do with the acts that have no table of their own
        # (the startle onset, a freeze, a flight): see skilltrain/guard.py and neuro/bodylink.py
        upright = ("stand", "walk")
        add("startle", upright, [*g.STARTLE_ORDER, *g.FREEZE_ORDER, g.HOP_ENTRY])
        add("freeze", upright, list(g.FREEZE_ORDER))
        add("flee", upright, [g.HOP_ENTRY, g.PANIC_ENTRIES[0]])
        add("retreat", upright, [g.PANIC_ENTRIES[0]])
        return {a: dict(by) for a, by in out.items()}

    def _check_brain_users(self) -> None:
        """A page motion the code says the brain uses must have a user here, or the list lies."""
        for m in self.motions.MOTIONS:
            if m.brain and m.brain not in ("corner", "pivot") and not self.users_of.get(m.entry):
                raise SystemExit(
                    f"motion_list: {m.id!r} says the brain uses it ({m.brain!r}) but no act asks "
                    f"for {m.entry!r}: teach Reg._entries_of"
                )

    def _users_of(self) -> dict[str, list[str]]:
        out: dict[str, list[str]] = defaultdict(list)
        for act in self.behaviours:
            for entries in self.entries_of.get(act, {}).values():
                for e in entries:
                    if act not in out[e]:
                        out[e].append(act)
        return out

    def render(self, value: Any, lang: str) -> str:
        return str(self._render(value, lang))


class Builder:
    """One language's file."""

    def __init__(self, reg: Reg, lang: str) -> None:
        self.r = reg
        self.lang = lang
        self.t: dict[str, Any] = TEXT[lang]
        self.w: dict[str, str] = self.t["w"]
        self.page = self._catalog("page")
        self.neuro = self._catalog("neuro")
        self.core = self._catalog("core")

    def _catalog(self, domain: str) -> dict[str, str]:
        got = self.r.read_catalog(self.lang, domain)
        if got is None:
            raise SystemExit(f"motion_list: no {domain} catalog for {self.lang}")
        return got

    # ── words ──────────────────────────────────────────────────────────────────────────────
    def msg(self, value: Any) -> str:
        return self.r.render(value, self.lang)

    def pg(self, key: str) -> str:
        try:
            text = self.page[key]
        except KeyError:
            raise SystemExit(f"motion_list: no page catalog key {key!r} in {self.lang}") from None
        if "{" in text:
            raise SystemExit(f"motion_list: {key!r} has a placeholder; the list cannot show it")
        return text

    def par(self, text: str) -> str:
        return f"{self.t['open']}{text}{self.t['close']}"

    def ids(self, names: Any) -> str:
        return self.t["sep"].join(f"`{n}`" for n in names)

    def verdict(self, family: str) -> str:
        return self.pg("page.motion.verdict." + self.r.mt.VERDICT[family]["verdict"])

    def postures(self, postures: Any) -> str:
        ordered = [p for p in POSTURE_ORDER if p in postures]
        return self.t["sep"].join(self.pg("page.motion.posture." + p) for p in ordered)

    def sounds(self, tags: tuple[str, ...]) -> str:
        parts = [self.w["silent"]] if "" in tags else []
        parts += [self.neuro["neuro.vocal." + tag] for tag in tags if tag]
        return self.t["sep"].join(parts)

    def yes(self, flag: bool) -> str:
        return self.w["yes" if flag else "no"]

    # ── Runs on ────────────────────────────────────────────────────────────────────────────
    def skill_words(self, entries: list[str]) -> str:
        run = self.t["run"]
        if len(entries) <= 2:
            return run["skill"].format(entries=self.ids(entries))
        families = list(dict.fromkeys(self.r.g.DEFAULT_RULES[e].family for e in entries))
        return run["skill_family"].format(families=self.ids(families))

    def program(self, posture: str) -> str:
        return self.t["run"]["program_" + {"stand": "stand", "sit": "sit"}.get(posture, "any")]

    def reflex_runs(self, act: str) -> str:
        key = REFLEX_RUNS[act]
        text = self.t["reflex_runs"][key]
        if key == "skills":
            entries = [e for es in self.r.entries_of[act].values() for e in es]
            families = dict.fromkeys(self.r.g.DEFAULT_RULES[e].family for e in entries)
            return text.format(families=self.ids(families))
        if key == "righting":
            entry, chance, _patience = self.r.g.BRAIN_AFTER[act]
            return text.format(chance=chance, entry=entry)
        return text

    def runs_on(self, act: str) -> str:
        r, run = self.r, self.t["run"]
        if act in REFLEX_RUNS:
            return self.reflex_runs(act)
        spec = r.behaviours[act]
        if act in POSTURE_CHANGE:
            return run["sitstand"]
        by = r.entries_of.get(act, {})
        base = run["walk"] if spec.locomotes else self.program(spec.posture)
        if not by:
            return base
        every = list(dict.fromkeys(e for es in by.values() for e in es))
        if spec.locomotes:
            return run["plus"].format(base=base, skill=self.skill_words(every))
        need = {"stand", "sit"} if spec.posture == "any" else {spec.posture}
        if need <= set(by) and len(by) == 1:
            return self.skill_words(every)
        parts = [
            run["when"].format(
                skill=self.skill_words(by[p]), posture=self.pg("page.motion.posture." + p)
            )
            for p in POSTURE_ORDER
            if p in by
        ]
        if not need <= set(by):
            parts.append(run["otherwise"])
        return self.t["semi"].join(parts)

    # ── Trigger ────────────────────────────────────────────────────────────────────────────
    def triggers(self, act: str) -> str:
        r, w = self.r, self.w
        words = [] if act in r.trick_only else [w["autonomous"]]
        verbs = r.claims_of.get(act, [])
        if any(v in r.cw.BUILTIN for v in verbs):
            words.append(w["command"])
        if any(v in r.cw.TRICKS for v in verbs):
            words.append(w["trick"])
        return self.t["sep"].join(words)

    # ── behaviour tables (sections 2, 5 and 7) ─────────────────────────────────────────────
    def behaviour_row(self, act: str, *, branch: bool = False) -> list[str]:
        spec = self.r.behaviours[act]
        posture = (
            self.w["any_posture"]
            if spec.posture == "any"
            else self.pg("page.motion.posture." + spec.posture)
        )
        if spec.sleep:
            posture += self.par(self.w["asleep"])
        row = [
            f"`{act}`",
            self.msg(spec.zh),
            self.msg(spec.body_zh),
            self.triggers(act),
            posture,
            self.yes(spec.locomotes),
            spec.unlock_gd,
        ]
        if branch:
            row.append(self.core[f"core.content.BRANCHES.{spec.branch}_zh"])
        return [*row, self.sounds(spec.sounds), self.runs_on(act)]

    def behaviour_table(self, acts: list[str], *, branch: bool = False) -> list[str]:
        head = list(self.t["b_head"])
        if branch:
            head.insert(7, self.t["branch"])
        return table(head, [self.behaviour_row(a, branch=branch) for a in acts])

    # ── sections ───────────────────────────────────────────────────────────────────────────
    def intro(self) -> list[str]:
        r, t, w = self.r, self.t, self.w
        n = {fam: len(ids) for fam, ids in r.s7_ids.items()}
        total_7 = sum(n.values())
        cmds = (len(r.cw.BUILTIN), len(r.cw.TRICKS), len(r.cw.POINTED))
        counts = [
            [t["s1_h"], len(self.gait_rows())],
            [t["s2_h"], len(r.s2_ids)],
            [
                t["s3_h"],
                t["counts_skills"].format(skills=len(r.rules), buttons=len(r.motions.MOTIONS)),
            ],
            [t["s4_h"], len(r.emo.ORDER)],
            [t["s5_h"], len(r.s5_ids)],
            [
                t["s6_h"],
                t["counts_cmds"].format(
                    n=sum(cmds), builtin=cmds[0], tricks=cmds[1], pointed=cmds[2]
                ),
            ],
            [t["s7_h"], total_7],
        ]
        words = {
            **w,
            "passed": self.pg("page.motion.verdict.pass"),
            "limits": self.pg("page.motion.verdict.limits"),
            "fail": self.pg("page.motion.verdict.fail"),
        }
        legend = [[f"**{term}**", text.format(**words)] for term, text in t["legend"]]
        s2_acts = len(r.s2_ids)
        s5_acts = sum(1 for b in r.s5_ids if b in r.behaviours)
        return [
            f"# {t['title']}",
            "",
            f"## {t['about_h']}",
            "",
            *[line for para in t["about"] for line in (para, "")],
            t["status"],
            "",
            f"### {t['counts_h']}",
            "",
            *table(t["counts_head"], counts),
            "",
            t["counts_note"].format(total=len(r.behaviours), n2=s2_acts, n5=s5_acts, n7=total_7),
            "",
            f"### {t['legend_h']}",
            "",
            *table(t["legend_head"], legend),
        ]

    def gait_rows(self) -> list[list[Any]]:
        r, t, w = self.r, self.t, self.w
        c, g, mt = r.c, r.g, r.mt
        rule = g.DEFAULT_RULES
        qt = rule[g.QUICK_TURN_ENTRIES[0]]
        panic = rule[g.PANIC_ENTRIES[0]]
        back = r.prims.back_arc(True)
        arcs = self.ids(e for e in g.PANIC_ENTRIES if e != g.PANIC_ENTRIES[0])
        fmt = {
            "min": f"{c.MIN_STEP_VX:.2f}",
            "max": f"{c.NORMAL_VX_MAX:.2f}",
            "approach": f"{c.APPROACH_VX:.2f}",
            "arc": f"{c.ARC_VX_MIN:.2f}",
            "yaw": f"{c.VYAW_MAX:.1f}",
            "rev": f"{c.REVERSE_VX:.2f}",
            "rev_min": f"{-c.MIN_STEP_VX:.2f}",
            "back_yaw": f"{c.BACK_ARC_VYAW:.1f}",
            "back_s": f"{back.ms / 1000:g}",
            "corner_s": f"{r.brain.CORNER_BACK_MS / 1000:g}",
            "backs": r.brain.CORNER_BACKS,
            "dock": f"{c.DOCK_VX_MIN:.2f}",
            "qt_min": f"{g.QUICK_TURN_MIN_YAW:.1f}",
            "qt_yaw": f"{mt.QTURN_YAW:.1f}",
            "panic_cmd": f"{mt.PANIC_COMMANDS[0][1][0]:.1f}",
            "panic_min": f"{r.motor.PANIC_VX_MIN:.2f}",
            "arcs": (t["panic_arcs_on"] if g.ARCS_ON else t["panic_arcs_off"]).format(arcs=arcs),
        }

        def text(row: str, key: str, **more: Any) -> str:
            return t["gait"][row][key].format(**fmt, **more)

        def skill(entries: Any) -> str:
            return t["run"]["skill"].format(entries=self.ids(entries))

        def turn_fmt(name: str) -> dict[str, Any]:
            x = rule[name]
            tilt = x.abort_tilt_deg if x.abort_tilt_deg is not None else g.ABORT_TILT_DEG
            return {
                "walk": f"{x.max_walk_mps:.2f}",
                "cap": x.per_hour,
                "gap": f"{x.min_gap_s:g}",
                "tilt": f"{tilt:g}",
            }

        walkers = [v for v in r.cw.BUILTIN if r.behaviours[r.cb.BEHAVIOUR_OF[v]].locomotes]
        walk_verbs = self.ids([*walkers, *r.cw.POINTED])
        auto = w["autonomous"]
        turn_entries = ["turn_left", "turn_right"]
        rows: list[list[Any]] = []

        def add(row: str, ident: str, runs: str, trigger: str, status: str, **more: Any) -> None:
            rows.append(
                [
                    ident,
                    text(row, "what", **more),
                    text(row, "speed", **more),
                    runs,
                    trigger,
                    text(row, "safety", **more),
                    status,
                ]
            )

        walking = t["run"]["walk"]
        dash = w["dash"]
        add(
            "walk",
            "`walk`",
            walking,
            t["walk_triggers"].format(autonomous=auto, command=w["command"], verbs=walk_verbs),
            dash,
        )
        add("approach", "`approach`", walking, auto, dash)
        add("arc", "`arc`", walking, auto, dash)
        add("back_arc", "`back_arc`", walking, auto, dash)
        add(
            "reverse",
            "`reverse`",
            walking,
            f"{auto}{t['semi']}{w['command']}{self.par(self.ids(['go_home']))}",
            dash,
        )
        add(
            "turn",
            self.ids(turn_entries),
            skill(turn_entries),
            f"{auto}{self.par(t['corner'])}{t['semi']}{w['page_demo']}",
            self.verdict(rule["turn_left"].family),
            **turn_fmt("turn_left"),
        )
        add(
            "quick_turn",
            self.ids(g.QUICK_TURN_ENTRIES),
            skill(g.QUICK_TURN_ENTRIES),
            f"{auto}{self.par(t['pivot'])}{t['semi']}{w['page_demo']}",
            self.verdict(qt.family),
            **turn_fmt(g.QUICK_TURN_ENTRIES[0]),
        )
        add(
            "panic",
            self.ids(g.PANIC_ENTRIES),
            t["run"]["or_walk"].format(skill=skill([g.PANIC_ENTRIES[0]])),
            f"{auto}{self.par(self.ids(['flee', 'retreat']))}",
            self.verdict(panic.family),
            **turn_fmt(g.PANIC_ENTRIES[0]),
        )
        return rows

    def section_gaits(self) -> list[str]:
        t, c = self.t, self.r.c
        return [
            f"## {t['s1_h']}",
            "",
            t["s1_intro"].format(min=f"{c.MIN_STEP_VX:.2f}"),
            "",
            *table(t["s1_head"], self.gait_rows()),
        ]

    def section_posture(self) -> list[str]:
        t = self.t
        return [
            f"## {t['s2_h']}",
            "",
            t["s2_intro"],
            "",
            *self.behaviour_table(self.r.s2_ids),
        ]

    def used_by(self, entry: str) -> str:
        r, t, w, g = self.r, self.t, self.w, self.r.g
        used = [f"`{a}`" for a in r.users_of.get(entry, []) if a not in r.trick_only]
        used += [t["after"].format(act=f"`{a}`") for a in r.after_of.get(entry, [])]
        brains = {m.brain for m in r.motion_by_entry.get(entry, [])}
        used += [t[b] for b in ("corner", "pivot") if b in brains]
        for verb in r.cw.TRICKS:
            asked = r.entries_of.get(r.cb.BEHAVIOUR_OF[verb], {})
            if entry in [e for es in asked.values() for e in es]:
                used.append(t["trick_word"].format(verb=f"`{verb}`"))
        if entry in r.motion_by_entry:
            used.append(w["page_demo"])
        if not used and entry in g.PANIC_ENTRIES and not g.ARCS_ON:
            used.append(t["arcs_off"])
        return t["sep"].join(used) or w["dash"]

    def skill_rows(self) -> list[list[Any]]:
        r, w, g = self.r, self.w, self.r.g
        rows = []
        for name, rule in r.rules.items():
            motions = r.motion_by_entry.get(name, [])
            page_name = self.t["sep"].join(self.pg(r.words[m.id][0]) for m in motions)
            tilt = rule.abort_tilt_deg if rule.abort_tilt_deg is not None else g.ABORT_TILT_DEG
            walks = "walk" in rule.postures and rule.max_walk_mps is not None
            rows.append(
                [
                    f"`{name}`" + ("" if name in r.installed else " †"),
                    page_name or w["dash"],
                    rule.family,
                    self.postures(rule.postures),
                    w["no_cap"] if rule.per_hour is None else rule.per_hour,
                    f"{rule.min_gap_s:g}" if rule.min_gap_s else w["dash"],
                    f"{rule.max_walk_mps:.2f}" if walks else w["dash"],
                    w["never"] if tilt >= 360 else f"{tilt:g}",
                    self.verdict(rule.family),
                    self.used_by(name),
                ]
            )
        return rows

    def button_rows(self) -> list[list[Any]]:
        r, t = self.r, self.t
        rows = []
        for m in r.motions.MOTIONS:
            name_key, limit_key = r.words[m.id]
            brain_key = r.brain_words.get(m.id, r.no_brain)
            starts = f"`{m.entry}`"
            if m.then:
                starts = t["then"].format(entry=starts, then=f"`{m.then}`")
            rows.append(
                [
                    f"`{m.id}`",
                    self.pg(name_key),
                    self.pg("page.motion.group." + m.group),
                    starts,
                    self.pg(brain_key),
                    self.pg(limit_key),
                    self.pg("page.motion.verdict." + m.verdict),
                ]
            )

        return rows

    def section_skills(self) -> list[str]:
        r, t, g = self.r, self.t, self.r.g
        missing = [n for n in r.rules if n not in r.installed]
        more = [
            t["s3_more"][0].format(
                release=f"`{g.RELEASE}`", bow_release=f"`{g.BOW_RELEASE}`", abort=f"`{g.ABORT}`"
            ),
            t["s3_more"][1].format(
                max_tilt=f"{g.MAX_TILT_DEG:g}", n_missing=len(missing), slots=r.slots
            ),
        ]
        return [
            f"## {t['s3_h']}",
            "",
            t["s3_intro"],
            "",
            *[
                f"- {rule.format(global_cap=g.GLOBAL_PER_HOUR, never=self.w['never'])}"
                for rule in t["s3_rules"]
            ],
            "",
            *[line for para in more for line in (para, "")],
            f"### {t['s3a_h']}",
            "",
            *table(t["s3_head"], self.skill_rows()),
            "",
            f"### {t['s3b_h']}",
            "",
            t["s3b_intro"].format(tab=self.pg("page.motion.title")),
            "",
            *table(t["s3b_head"], self.button_rows()),
        ]

    def section_emotions(self) -> list[str]:
        r, t = self.r, self.t
        e = r.emo
        rows = []
        for name in e.ORDER:
            brain_key = r.brain_words.get(e.ID_PREFIX + name, r.no_brain)
            if (name in e.BRAIN_USE) == (brain_key == r.no_brain):
                raise SystemExit(f"motion_list: emotion {name!r}: BRAIN_USE and neuro.js disagree")
            runs_key = (
                "keyframes_dead"
                if name == LEG_EMOTION
                else "keyframes_sit"
                if name in e.SIT
                else "keyframes"
            )
            trigger = [self.w["page_demo"]]
            if name in e.BRAIN_USE:
                trigger.insert(0, self.w["autonomous"])
            rows.append(
                [
                    f"`{name}`",
                    self.pg(f"page.emotion.name.{name}"),
                    self.pg(f"page.emotion.desc.{name}"),
                    t["sep"].join(trigger),
                    self.yes(name in e.SIT),
                    self.pg(brain_key),
                    f"{e.COOLDOWN_S[name]:g}",
                    t["run"][runs_key],
                    self.pg("page.motion.verdict." + e.VERDICT[name]),
                ]
            )
        intro = [
            t["s4_intro"][0].format(n=len(e.ORDER)),
            t["s4_intro"][1].format(gap=f"{e.GAP_S:g}"),
            t["s4_intro"][2].format(sit=self.pg("page.emotion.desc.play_dead_sit")),
        ]
        return [
            f"## {t['s4_h']}",
            "",
            *[line for para in intro for line in (para, "")],
            *table(t["s4_head"], rows),
        ]

    def section_reflexes(self) -> list[str]:
        r, t, w = self.r, self.t, self.w
        rows = []
        for act in r.s5_ids:
            for table_name, table_ in (("REFLEX_WHY", REFLEX_WHY), ("REFLEX_RUNS", REFLEX_RUNS)):
                if act not in table_:
                    raise SystemExit(
                        f"motion_list: no words for reflex {act!r}: add it to {table_name}"
                    )
            spec = r.behaviours.get(act)
            reflex = r.c.REFLEXES.get(act)
            rows.append(
                [
                    f"`{act}`",
                    self.msg(reflex) if reflex is not None else w["dash"],
                    self.msg(spec.zh) if spec is not None else w["dash"],
                    self.msg(spec.body_zh) if spec is not None else w["dash"],
                    REFLEX_WHY[act][self.lang],
                    self.sounds(spec.sounds) if spec is not None else w["dash"],
                    self.runs_on(act),
                ]
            )
        extra = sorted(set(REFLEX_WHY) - set(r.s5_ids))
        if extra:
            raise SystemExit(f"motion_list: REFLEX_WHY has words for unknown reflexes {extra}")
        return [f"## {t['s5_h']}", "", t["s5_intro"], "", *table(t["s5_head"], rows)]

    def phrases(self, verb: str) -> str:
        q = self.t["quote"]
        found = self.r.cw.PHRASES[verb][self.lang][:PHRASES_SHOWN]
        return self.t["sep"].join(f"{q[0]}{p.lstrip('=')}{q[1]}" for p in found)

    def command_rows(self) -> list[list[Any]]:
        r, t = self.r, self.t
        tr = r.tricks
        rows = []
        order = [("builtin", v) for v in r.cw.BUILTIN]
        order += [("trick", v) for v in r.cw.TRICKS] + [("pointed", v) for v in r.cw.POINTED]
        for kind, verb in order:
            if verb == "go_there":
                act, name, say = "wander", t["go_there_name"], t["go_there_say"]
                claims = t["go_there_claims"].format(walk=f"`{act}`")
            else:
                act = r.cb.BEHAVIOUR_OF[verb]
                name, say = self.pg("page.cmd.verb." + verb), self.phrases(verb)
                claims = f"`{act}` {self.msg(r.behaviours[act].zh)}"
            notes = []
            if verb == "go_there":
                notes.append(
                    t["note_errand"].format(
                        base=r.errand.BUDGET_BASE_S,
                        per=r.errand.BUDGET_PER_M,
                        far=r.errand.MAX_RANGE_M,
                    )
                )
            elif verb == "follow":
                notes.append(t["note_follow"].format(n=r.cb.DEADLINE_S[verb]))
            else:
                notes.append(t["note_limit"].format(n=r.cb.DEADLINE_S[verb]))
            twin = [v for v in r.cb.BEHAVIOUR_OF if r.cb.BEHAVIOUR_OF.get(v) == act and v != verb]
            if verb != "go_there" and twin and kind == "builtin":
                notes.append(t["note_both"].format(a=f"`{verb}`", b=self.ids(twin), act=f"`{act}`"))
            if verb in VERB_NOTES:
                notes.append(VERB_NOTES[verb][self.lang])
            for by_itself, trick in r.cb.SPONTANEOUS.items():
                if trick == verb and by_itself != act:
                    notes.append(
                        t["note_shaping"].format(win=tr.SHAPE_WINDOW_S, act=f"`{by_itself}`")
                    )
            if verb == "flip":
                roll = r.g.DEFAULT_RULES[r.g.ROLL_ENTRY]
                cb = r.cb
                notes.append(
                    t["note_flip"].format(
                        calm=cb.FLIP_CALM_S,
                        ahead=cb.FLIP_AHEAD_M,
                        around=cb.FLIP_AROUND_M,
                        battery=cb.FLIP_BATTERY,
                        cap=roll.per_hour,
                        gap=roll.min_gap_s,
                    )
                )
            rows.append(
                [
                    f"`{verb}`",
                    t["kind"][kind],
                    name,
                    say,
                    claims,
                    self.runs_on(act),
                    r.behaviours[act].unlock_gd,
                    t["note_sep"].join(notes),
                ]
            )

        return rows

    def section_commands(self) -> list[str]:
        r, t = self.r, self.t
        tr = r.tricks
        intro = [
            t["s6_intro"][0].format(n=PHRASES_SHOWN),
            t["s6_intro"][1],
            t["s6_intro"][2].format(
                base=tr.OBEY_BASE,
                cap=tr.CAP_PER_GD,
                learned=tr.LEARNED_AT,
                floor=tr.FLOOR,
                tau=tr.DECAY_TAU_GD,
            ),
        ]
        return [
            f"## {t['s6_h']}",
            "",
            *[line for para in intro for line in (para, "")],
            *table(t["s6_head"], self.command_rows()),
        ]

    def section_behaviours(self) -> list[str]:
        r, t = self.r, self.t
        tricks = self.ids(sorted(r.trick_only, key=list(r.behaviours).index))
        lines = [f"## {t['s7_h']}", "", t["s7_intro"].format(tricks=tricks)]
        for fam in FAMILY_ORDER:
            acts = r.s7_ids[fam]
            if not acts:
                continue
            title, blurb = t["family"][fam]
            lines += [
                "",
                f"### {title} (`{fam}`)",
                "",
                blurb,
                "",
                *self.behaviour_table(acts, branch=fam == "signature"),
            ]
        return lines

    def build(self) -> str:
        blocks = [
            [LANGUAGE_LINE[self.lang], "", GENERATED, ""],
            self.intro(),
            self.section_gaits(),
            self.section_posture(),
            self.section_skills(),
            self.section_emotions(),
            self.section_reflexes(),
            self.section_commands(),
            self.section_behaviours(),
        ]
        text = "\n\n".join("\n".join(block).strip("\n") for block in blocks)
        return text.replace("\n\n\n", "\n\n") + "\n"


def render_all() -> dict[str, str]:
    """File name -> text, for every language."""
    reg = Reg()
    return {FILES[lang]: Builder(reg, lang).build() for lang in LANGS}


def main(argv: list[str] | None = None, *, docs_dir: Path = DOCS) -> int:
    parser = argparse.ArgumentParser(description="Write the list of everything the duck can do.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if a file differs from what would be written",
    )
    args = parser.parse_args(argv)
    docs = render_all()
    if args.check:
        stale = [
            name
            for name, text in docs.items()
            if not (docs_dir / name).is_file()
            or (docs_dir / name).read_bytes() != text.encode("utf-8")
        ]
        if stale:
            print(
                f"out of date: {', '.join(stale)}; run: python tools/motion_list.py",
                file=sys.stderr,
            )
            return 1
        print("up to date")
        return 0
    for name, text in docs.items():
        (docs_dir / name).write_bytes(text.encode("utf-8"))
        print(f"wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
