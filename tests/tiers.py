"""The test tiers: what kind each test is, and which are too slow for the fast tier.

``tests/conftest.py`` reads these tables while pytest collects and puts the markers on the
tests, so a marker never has to be written in a test file:

- ``render``   every test in conftest's ``RENDER_FILES`` (numpy + MuJoCo's offscreen render);
- ``physics``  ``PHYSICS``: the test steps or compiles MuJoCo (it skips without the ``sim`` extra
               and the official duck model);
- ``node``     ``NODE``: the test runs a page script in Node (it skips without Node);
- ``subprocess`` ``SUBPROCESS``: the test starts a child process (a child pytest, a CLI, a server);
- ``timing``   ``TIMING``: the test sleeps or polls on the wall clock, so a busy machine can fail it;
- ``heavy``    every ``render`` and ``physics`` test, and ``SLOW``.

The fast tier is ``pytest -m "not heavy"`` (CONTRIBUTING.md): under three minutes on a laptop,
no MuJoCo. A plain ``pytest`` is still the whole suite.

A table maps a test file to the tests in it, by the name of the function (``Class.test`` inside a
class; every parameter of a parametrized test goes together), or to ``WHOLE`` for all of them. A
name that is not in its file stops the run (conftest checks): rename a test here too.

``SLOW`` is measured, not judged: a test whose slowest case took 0.5 s or more, or whose cases
together took 1 s or more, in the median of three whole-suite runs on the owner's Mac
(2026-11-09/10, 6,477 tests in about 29 minutes). The fast tier names its own tests that took
2 s or more when it ends: put those here. Take a test out when it has become fast. A test
that shares a slow test's cached run (a module-scoped fixture, an ``lru_cache``) is here with
it: whichever of them runs first pays for the run.
"""

