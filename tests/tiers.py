def listed(table: dict[str, tuple[str, ...]], file: str, test: str) -> bool:
    names = table.get(file, ())
    return names is WHOLE or test in names


def kinds(file: str, test: str) -> list[str]:
    """The kinds these tables give one test (``render`` and ``heavy`` are conftest's to add)."""
    return [name for name, table in _TABLES if listed(table, file, test)]


